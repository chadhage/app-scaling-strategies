'use strict';

// Deterministic generator for saved.js (no clock, no randomness). `--check` compares instead of writing.
const fs = require('node:fs');
const path = require('node:path');
const { savedFleets } = require('.\\fixtures.cjs');

const target = path.join(__dirname, '..', 'saved.js');
function render() {
  const lines = savedFleets().map((item) => {
    const clients = item.fleet.clients.map((client) => `        ${JSON.stringify(client)}`).join(',\n');
    return `    {\n      "id": ${JSON.stringify(item.id)}, "role": ${JSON.stringify(item.role)}, "negativeOf": ${JSON.stringify(item.negativeOf)},\n` +
      `      "label": ${JSON.stringify(item.label)},\n      "fleet": { "schema": "C031-fleet/1", "id": ${JSON.stringify(item.fleet.id)}, "clients": [\n${clients}\n      ] }\n    }`;
  });
  return `(function (root) {
  'use strict';
  function freeze(value) {
    if (value && typeof value === 'object') { Object.values(value).forEach(freeze); Object.freeze(value); }
    return value;
  }
  // Fictional saved per-client traces of a fictional v1 (1.0.0) to v2 (2.0.0) profile service migration.
  // Generated by tests/build-saved.cjs; the raw bytes are pinned in imports.json.
  const bundle = freeze({
    "bundleVersion": 1, "cardId": "C031", "fictional": true,
    "fleets": [
${lines.join(',\n')}
    ]
  });
  if (typeof module === 'object' && module.exports) module.exports = bundle;
  else Object.defineProperty(root, 'C031Saved', { value: bundle });
}(globalThis));
`;
}
module.exports = Object.freeze({ render, target });
if (require.main === module) {
  const bytes = Buffer.from(render(), 'utf8');
  if (process.argv[2] === '--check') {
    const same = fs.existsSync(target) && fs.readFileSync(target).equals(bytes);
    console.log(same ? 'saved.js matches the generator' : 'saved.js differs from the generator');
    process.exitCode = same ? 0 : 1;
  } else {
    fs.writeFileSync(target, bytes);
    console.log(`wrote ${bytes.length} bytes`);
  }
}
