'use strict';

// Writes saved.js: the saved runs the timeline page and the tests read. Console sessions come from the accepted C044 producer
// (manual scheduler, no timers), traces from the accepted C034 bundle, hostile sets are mutated copies. Run once:
//   node capability\X001\tests\build-saved.cjs          (refuses to overwrite; --force rewrites, --check compares)
const fs = require('node:fs');
const path = require('node:path');
const trace = require('..\\..\\C034\\trace.js');
const console_ = require('.\\scenarios-console.cjs');
const hostile = require('.\\scenarios-hostile.cjs');

const target = path.join(__dirname, '..', 'saved.js');
const header = `(function (root, factory) {
  'use strict';
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else Object.defineProperty(root, 'X001Saved', { value: factory() });
}(globalThis, function () {
  'use strict';
  // GENERATED by tests\\build-saved.cjs from the accepted C044 producer and the accepted C034 bundle. Do not edit: the pin in imports.json
  // and tests\\imports.test.cjs recompute it. Synthetic and fictional; not a live Azure result.
  function freeze(value) {
    if (value && typeof value === 'object') { Object.values(value).forEach(freeze); Object.freeze(value); }
    return value;
  }
  const runs = `;
const footer = `;
  return freeze({ schema: 'X001-saved/1', runs });
}));
`;

function runs() {
  const list = [console_.restartGap(), console_.complete(), console_.truncated(), hostile.hostileMix(), ...hostile.traces()];
  const ids = list.map((run) => run.id);
  if (new Set(ids).size !== ids.length) throw new Error('duplicate saved run id');
  for (const run of list.filter((entry) => entry.kind === 'trace')) {
    const verdict = trace.validateSnapshot(run.snapshot);
    if (Boolean(run.source.hostile) === verdict.valid) throw new Error(`${run.id}: decoder verdict ${verdict.valid}/${verdict.code} contradicts its intent`);
  }
  return list;
}

function buildText() { return `${header}${JSON.stringify(runs(), null, 1)}${footer}`; }

if (require.main === module) {
  const text = buildText();
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(target) && fs.readFileSync(target, 'utf8') === text;
    console.log(same ? 'saved.js matches the accepted producers' : 'saved.js DIFFERS');
    process.exitCode = same ? 0 : 1;
  } else if (fs.existsSync(target) && !process.argv.includes('--force')) {
    throw new Error('saved.js exists; pass --force to rebuild');
  } else {
    fs.writeFileSync(target, text);
    console.log(`wrote saved.js: ${runs().length} saved runs, ${text.length} characters`);
  }
}
module.exports = Object.freeze({ runs, buildText });
