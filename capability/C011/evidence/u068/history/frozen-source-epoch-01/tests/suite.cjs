'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..', '..', '..');
const mode = process.argv[2];
assert.ok(['core', 'final', 'red-replay'].includes(mode), 'explicit core, final or red-replay mode is required');
const directory = process.env.C011_ASSERTION_DIR;
assert.ok(directory && path.isAbsolute(directory), 'a fresh explicitly owned assertion directory is required');
assert.equal(fs.existsSync(directory), false, 'assertion output is never silently reused');
fs.mkdirSync(directory, { recursive: false });
let names = fs.readdirSync(__dirname).filter((name) => name.endsWith('.test.cjs')).sort();
if (mode === 'red-replay') names = ['reserve', 'race', 'idempotency', 'lifecycle', 'leaks', 'roles', 'hostile', 'batch', 'audit'].map((name) => name + '.test.cjs');
if (mode === 'final') names.push('u068-evidence-final.cjs');
const env = { ...process.env };
for (const name of ['NODE_TEST_CONTEXT', 'NODE_V8_COVERAGE', 'CAPTURE_BROWSER_EVIDENCE', 'C011_SUBJECT_DIR']) delete env[name];
const args = ['--require', path.join(__dirname, 'assertions-preload.cjs'), '--test', '--test-concurrency=1', '--test-timeout=180000',
  ...names.map((name) => path.join(__dirname, name))];
const result = spawnSync(process.execPath, args, { cwd: root, env, windowsHide: true, timeout: 1200000, maxBuffer: 128 * 1024 * 1024 });
process.stdout.write(result.stdout || '');
process.stderr.write(result.stderr || '');
assert.equal(result.error, undefined, 'an external timeout or spawn failure is not a pass');
const reports = fs.readdirSync(directory).filter((name) => name.endsWith('.json')).map((name) => JSON.parse(fs.readFileSync(path.join(directory, name))));
const tests = reports.reduce((sum, report) => sum + report.tests, 0);
const assertions = reports.reduce((sum, report) => sum + report.assertions, 0);
const zeroAssertionTests = reports.flatMap((report) => report.zeroAssertionTests);
const declared = Number(/^# tests (\d+)$/m.exec(result.stdout.toString('utf8'))?.[1] ?? -1);
console.log('C011_ASSERTIONS ' + JSON.stringify({ tests, declared, assertions, zeroAssertionTests }));
assert.equal(tests, declared, 'every executed named test has an assertion observation');
assert.ok(assertions > 0);
assert.deepEqual(zeroAssertionTests, [], 'no generated row or named test passes without an assertion');
process.exitCode = result.status === 0 ? 0 : 1;
