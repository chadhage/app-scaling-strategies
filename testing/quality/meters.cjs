// The fixture keeps its register free of GUID-shaped values: fixture-meter-N placeholders stand for the meters there.
const PLACEHOLDER = /^fixture-meter-\d{1,4}$/;

const isCatalogMeter = (id) => typeof id === 'string' && HASHES.has(crypto.createHash('sha256').update(id.toLowerCase()).digest('hex'));
const isPlaceholderMeter = (id) => typeof id === 'string' && PLACEHOLDER.test(id);

module.exports = { isCatalogMeter, isPlaceholderMeter, METER_COUNT: HASHES.size };
